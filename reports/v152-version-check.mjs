import fs from 'node:fs';
import { chromium } from 'playwright';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:390,height:844}});
await page.goto('http://127.0.0.1:5182/faakt.io/post/1007/',{waitUntil:'networkidle'});
await page.locator('.is-active .card-front .more-btn').click();
const version=await page.locator('.is-active .app-build-info').textContent();
if(!version.startsWith('v1.5.2 · build '))throw Error(version);
await page.screenshot({path:'reports/v152-review/version.png'});
await page.goto('http://127.0.0.1:5182/faakt.io/post/1/',{waitUntil:'networkidle'});
await page.waitForFunction(()=>document.querySelector('.is-active img')?.naturalWidth>0);
const old=JSON.parse(fs.readFileSync('static/data/posts.json','utf8')).find(p=>p.id==='1');
const title=await page.locator('.is-active .card-front h2').textContent();
if(title!==old.title)throw Error('Old card title mismatch');
await page.locator('.is-active .card-front .flip-btn').click();
await page.locator('.is-active .card-back .source-toggle').click();
const links=await page.locator('.is-active .card-back .source-list a').evaluateAll(as=>as.map(a=>a.href));
if(links.length!==old.sources.length)throw Error('Old sources mismatch');
const result={version,legacyCard:'1',title,imageDecoded:true,flipped:true,sources:links};
fs.writeFileSync('reports/v152-version-validation.json',JSON.stringify(result,null,2)+'\n');
await browser.close();console.log(JSON.stringify(result));
