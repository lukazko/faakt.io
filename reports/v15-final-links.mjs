import { chromium } from 'playwright';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const base='http://127.0.0.1:4195/faakt.io/';
const posts=JSON.parse(readFileSync('static/data/posts.json','utf8'));
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:390,height:844}});
await page.emulateMedia({reducedMotion:'reduce'});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
const first=base+'post/353/';
const response=await page.goto(first);
const front=page.locator('.is-active .card-front');
await front.locator('h2').filter({hasText:posts.find(p=>p.id==='353').title}).waitFor();
await front.locator('img').evaluate(image=>image.decode());
await page.locator('.is-active .card-front').getByRole('button',{name:'Další možnosti'}).click();
const version=await page.locator('.is-active .card-front .app-build-info').textContent();
if(!version.startsWith('v1.5.0')||response.status()!==200)throw Error('Wrong first link');
const sport=base+'?category=sport&post=378';
await page.goto(sport);await page.getByRole('button',{name:'Zrušit filtr kategorie Sport'}).waitFor();
if(await page.locator('.card-front .category-badge').count()!==5)throw Error('Wrong sport link');
const image=await fetch(base+'illustrations-ai/362.webp').then(r=>r.arrayBuffer());
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
if(hash(Buffer.from(image))!==hash(readFileSync('static/illustrations-ai/362.webp')))throw Error('Stale corrected image');
await browser.close();
if(errors.length)throw Error(errors.join('\n'));
writeFileSync('reports/v15-live-links.json',JSON.stringify({first,sport,version,status:200,correctedImageVerified:true,runtimeErrors:errors},null,2)+'\n');
console.log('Verified live links',first,sport,version);
