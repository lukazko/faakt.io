import {chromium} from 'playwright';
import {readFileSync} from 'node:fs';
const b=await chromium.launch({headless:true});console.log('launched');
const p=await b.newPage({viewport:{width:390,height:844}});
p.on('pageerror',e=>console.log('PAGE ERROR',e.message));
await p.route('**/data/posts.json',r=>r.fulfill({json:JSON.parse(readFileSync('reports/new-posts-927-956.json','utf8')).map(({knowledge,...p})=>p)}));
await p.goto('http://127.0.0.1:4189/faakt.io/?order=id&post=927',{waitUntil:'domcontentloaded',timeout:60000});console.log('loaded');
await p.locator('article').first().waitFor({timeout:30000});
console.log(await p.locator('article').first().evaluate(el=>({id:el.id,text:el.innerText.slice(0,200),images:[...el.querySelectorAll('img')].map(i=>({src:i.src,complete:i.complete}))})));
await p.screenshot({path:'tmp/imagegen-batch-927/debug-card.png'});await b.close();
